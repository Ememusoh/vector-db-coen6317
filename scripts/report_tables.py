"""Compact LaTeX tables, number macros and figure copies for the report.

Reads the results written by the experiment scripts and writes
    report/generated/numbers.tex      \\newcommand macros for every number quoted in the text
    report/generated/tab_*.tex        compact tables (tabular only; captions live in main.tex)
    report/figures/*.pdf              copies of results/figures (so report/ compiles on its own)

Usage: python scripts/report_tables.py
"""
from __future__ import annotations

import json
import shutil
import sys
from pathlib import Path

import numpy as np
import pandas as pd

ROOT = Path(__file__).resolve().parents[1]
RES = ROOT / "results"
OUT = ROOT / "report" / "generated"
sys.path.insert(0, str(ROOT))
from vdb.data.datasets import schemes  # noqa: E402

ORDER = ["sift", "gist", "glove", "deep", "yfcc"]
NAMES = {"sift": "SIFT1M", "gist": "GIST-500K", "glove": "GloVe-100", "deep": "Deep1M", "yfcc": "YFCC-1M"}
MACRO = {"sift": "Sift", "gist": "Gist", "glove": "Glove", "deep": "Deep", "yfcc": "Yfcc"}
PLAN_ABBR = {"prefilter": "Pre", "ivf_post": "IVF-post", "ivf_in": "IVF-in", "ivfpart_in": "PIVF-in",
             "hnsw_post": "HNSW-post", "hnsw_in": "HNSW-in"}
MNAME = {"planner": "Planner", "threshold": "Threshold", "fixed": "Fixed", "planner_global": "Global",
         "planner_cutoff": "Cutoff", "oracle": "Oracle"}
TARGET = 0.95


def available():
    return [d for d in ORDER if (RES / "raw" / f"{d}_planner_test.parquet").exists()]


class Macros:
    def __init__(self):
        self.lines = []

    def add(self, name, value, fmt="{:.2f}"):
        v = "--" if value is None or (isinstance(value, float) and not np.isfinite(value)) else fmt.format(value)
        self.lines.append(f"\\newcommand{{\\{name}}}{{{v}}}")

    def write(self, path):
        path.write_text("% generated by scripts/report_tables.py\n" + "\n".join(self.lines) + "\n")


def fmt_ms(v):
    return "--" if not np.isfinite(v) else (f"{v:.3f}" if v < 1 else f"{v:.2f}" if v < 10 else f"{v:.1f}")


def tabular(cols, header, rows, note=None):
    out = [rf"\begin{{tabular}}{{{cols}}}", r"\toprule", header + r" \\", r"\midrule"]
    out += [r + r" \\" for r in rows]
    out += [r"\bottomrule", r"\end{tabular}"]
    return "\n".join(out) + "\n"


def matched(dsets, mac):
    f = RES / "matched_recall.csv"
    if not f.exists():
        return
    df = pd.read_csv(f)
    df = df[(df.scope == "all") & np.isclose(df.target, TARGET) & df.dataset.isin(dsets)]
    methods = [("planner", "Planner"), ("threshold", "Threshold"), ("fixed", "Best fixed"),
               ("planner_global", "Global-only"), ("oracle", "Oracle")]
    rows = []
    speed, gaps = [], []
    for ds in dsets:
        d = df[df.dataset == ds].set_index("method")
        if d.empty:
            continue
        cells = []
        for m, _ in methods:
            if m in d.index:
                cells.append(f"{d.loc[m, 'recall']:.3f} & {fmt_ms(d.loc[m, 'mean_ms'])}")
                mac.add(f"mr{MACRO[ds]}{MNAME[m]}Ms", d.loc[m, "mean_ms"], "{:.2f}")
                mac.add(f"mr{MACRO[ds]}{MNAME[m]}Rec", d.loc[m, "recall"], "{:.3f}")
            else:
                cells.append("-- & --")
        sp = d.loc["threshold", "mean_ms"] / d.loc["planner", "mean_ms"]
        so = d.loc["planner", "mean_ms"] / d.loc["oracle", "mean_ms"]
        sg = d.loc["planner_global", "mean_ms"] / d.loc["planner", "mean_ms"]
        speed.append(sp)
        gaps.append(so)
        mac.add(f"mr{MACRO[ds]}Speedup", sp, "{:.1f}")
        mac.add(f"mr{MACRO[ds]}OracleGap", so, "{:.1f}")
        mac.add(f"mr{MACRO[ds]}GlobalSlowdown", sg, "{:.1f}")
        rows.append(f"{NAMES[ds]} & " + " & ".join(cells) + f" & {sp:.1f}$\\times$")
    mac.add("mrSpeedupMin", min(speed), "{:.1f}")
    mac.add("mrSpeedupMax", max(speed), "{:.1f}")
    mac.add("mrOracleGapMin", min(gaps), "{:.1f}")
    mac.add("mrOracleGapMax", max(gaps), "{:.1f}")
    head = " & " + " & ".join(rf"\multicolumn{{2}}{{c}}{{{n}}}" for _, n in methods) + r" & Speed-up \\" + "\n"
    head += " ".join(rf"\cmidrule(lr){{{2 + 2 * i}-{3 + 2 * i}}}" for i in range(len(methods))) + "\n"
    head += "Dataset & " + " & ".join(["R@10 & ms"] * len(methods)) + " & vs. thr."
    (OUT / "tab_matched.tex").write_text(tabular("l" + "rr" * len(methods) + "r", head, rows))

    # recall-target sweep summary: in how many (dataset, target) cells does the planner beat the threshold rule
    a = pd.read_csv(f)
    a = a[(a.scope == "all") & a.dataset.isin(dsets)]
    p = a[a.method == "planner"].set_index(["dataset", "target"]).mean_ms
    t = a[a.method == "threshold"].set_index(["dataset", "target"]).mean_ms
    wins = (p < t).sum()
    mac.add("mrWins", wins, "{:d}")
    mac.add("mrCells", len(p), "{:d}")


def live(dsets, mac):
    rows = []
    for ds in dsets:
        p = pd.read_parquet(RES / "raw" / f"{ds}_planner_test.parquet")
        for m in ("planner", "threshold", "fixed"):
            d = p[p.plan == m]
            mac.add(f"live{MACRO[ds]}{m.title()}Ms", d.latency_ms.mean())
            mac.add(f"live{MACRO[ds]}{m.title()}Rec", d.recall.mean(), "{:.3f}")
            mac.add(f"live{MACRO[ds]}{m.title()}Pninetyfive", np.percentile(d.latency_ms, 95))
            for s in schemes(ds):
                mac.add(f"live{MACRO[ds]}{m.title()}{s.title()}Rec", d[d.scheme == s].recall.mean(), "{:.3f}")
        pl, th = p[p.plan == "planner"], p[p.plan == "threshold"]
        ov = pl.overhead_ms.mean() * 1e3
        sp = th.latency_ms.mean() / pl.latency_ms.mean()
        mac.add(f"live{MACRO[ds]}OverheadUs", ov, "{:.0f}")
        mac.add(f"live{MACRO[ds]}Speedup", sp, "{:.1f}")
        rows.append(f"{NAMES[ds]} & {pl.recall.mean():.3f} & {fmt_ms(pl.latency_ms.mean())} & "
                    f"{fmt_ms(np.percentile(pl.latency_ms, 95))} & {th.recall.mean():.3f} & {fmt_ms(th.latency_ms.mean())} & "
                    f"{fmt_ms(np.percentile(th.latency_ms, 95))} & {sp:.1f}$\\times$ & {ov:.0f}")
    head = (r" & \multicolumn{3}{c}{Planner} & \multicolumn{3}{c}{Threshold rule} & & \\" + "\n"
            + r"\cmidrule(lr){2-4} \cmidrule(lr){5-7}" + "\n"
            + r"Dataset & R@10 & mean & p95 & R@10 & mean & p95 & Speed-up & $\mu$s")
    (OUT / "tab_live.tex").write_text(tabular("lrrrrrrrr", head, rows))


def best_plan(dsets, mac):
    rows = []
    n_pre_low = n_low = 0
    for ds in dsets:
        for s in schemes(ds):
            f = next((RES / f"{ds}_{s}_{sp}_summary.csv" for sp in ("test", "val")
                      if (RES / f"{ds}_{s}_{sp}_summary.csv").exists()), None)
            if f is None:
                continue
            df = pd.read_csv(f)
            cells = []
            for sel in sorted(df.selectivity.unique(), reverse=True):
                d = df[df.selectivity == sel]
                ok = d[d.recall >= TARGET].sort_values("p50_ms")
                if ok.empty:
                    cells.append("--")
                    continue
                b = ok.iloc[0]
                pre = d[d.plan == "prefilter"].p50_ms.iloc[0]
                txt = PLAN_ABBR[b.plan] + ("" if b.plan == "prefilter" else f"/{int(b.budget)}")
                gain = pre / b.p50_ms
                cells.append(f"{txt} ({gain:.0f}$\\times$)" if b.plan != "prefilter" and gain >= 1.5 else txt)
                if sel <= 0.011:
                    n_low += 1
                    n_pre_low += b.plan == "prefilter"
            label = {"independent": "ind.", "correlated": "corr.", "native": "tags"}[s]
            rows.append(f"{NAMES[ds]} & {label} & " + " & ".join(cells))
    mac.add("bestPreLow", n_pre_low, "{:d}")
    mac.add("bestLowCells", n_low, "{:d}")
    head = r"Dataset & Labels & 50\% & 10\% & 1\% & 0.1\%"
    (OUT / "tab_bestplan.tex").write_text(tabular("llllll", head, rows))


def datasets_table(dsets, mac):
    rows = []
    for ds in dsets:
        meta = json.loads((ROOT / "datasets" / ds / "meta.json").read_text())
        idx = ROOT / "indexes" / ds
        ivf = json.loads(next(idx.glob("ivf_*.json")).read_text())
        hnsw = json.loads(next(idx.glob("hnsw_*.json")).read_text())
        z = np.load(next(idx.glob("hnsw_*.npz")))
        graph = sum(z[k].nbytes for k in ("neighbors", "offsets", "cum", "levels")) / 2**20
        raw = meta["n_base"] * meta["dim"] * 4 / 2**20
        sch = "tags" if ds == "yfcc" else "synth."
        n = meta["n_base"]
        rows.append(f"{NAMES[ds]} & {n / 1e6:g}M & {meta['dim']} & {sch} & {raw:.0f} & "
                    f"{ivf['build_seconds']:.0f} & {hnsw['build_seconds']:.0f} & {graph:.0f}")
    head = r"Dataset & $N$ & $d$ & Labels & Vec.\,MiB & IVF\,s & HNSW\,s & Graph\,MiB"
    (OUT / "tab_datasets.tex").write_text(tabular("lrrlrrrr", head, rows))
    mac.add("nDatasets", len(dsets), "{:d}")


def copy_figures():
    dst = ROOT / "report" / "figures"
    dst.mkdir(parents=True, exist_ok=True)
    for f in (RES / "figures").glob("*.pdf"):
        shutil.copy2(f, dst / f.name)


def main():
    OUT.mkdir(parents=True, exist_ok=True)
    dsets = available()
    mac = Macros()
    matched(dsets, mac)
    live(dsets, mac)
    best_plan(dsets, mac)
    datasets_table(dsets, mac)
    mac.write(OUT / "numbers.tex")
    copy_figures()
    print(f"datasets: {', '.join(dsets)} -> {OUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
